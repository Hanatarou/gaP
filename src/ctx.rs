/// Tasks generated by the program itself ("PROG" lines of the original).
/// They keep paths/values that are ALREADY expanded — there is no double macro expansion.
#[derive(Clone, Debug)]
pub enum Prog {
    LtrDir { src: String, tgt: String, mv: bool, ow: bool },
    LtrFile { src: String, tgt: String, mv: bool, ow: bool },
    RegExport { key: String, file: String, view: reg::View },
    MinusRegKey { key: String, if_empty: bool, view: reg::View },
    /// Puts the key saved in `backup` back in `key` (see `ops_reg::restore_key`).
    RestoreRegKey { key: String, backup: String, view: reg::View },
    MinusRegValue { key: String, name: String, view: reg::View },
    LtrRegValue { src: String, tgt: String, mv: bool, view: reg::View },
    SymlinkRemove { link: String, is_dir: bool },
    /// Removes empty parent keys under HKCU/HKLM\Software (behavior described in the help).
    CleanParents { key: String, view: reg::View },
}

#[derive(Clone, Debug)]
pub enum TaskKind {
    /// Item written by the user in the .ini: normalized keyword + arguments.
    User { kw: String, args: Vec<String>, raw_key: String, raw_val: String },
    Done,
}

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Section {
    Before,
    After,
}

impl Section {
    pub fn name(self) -> &'static str {
        match self {
            Section::Before => "BEFORE",
            Section::After => "AFTER",
        }
    }
}

/// Where the debug log is, how many errors and warnings it got and when the run started: the line that ends the
/// log is written by whoever ends the program (see `log_end`), which has no `Ctx`.
static LOG_PATH: Mutex<Option<String>> = Mutex::new(None);
static ERRORS: AtomicU32 = AtomicU32::new(0);
static WARNINGS: AtomicU32 = AtomicU32::new(0);
static ENDED: AtomicBool = AtomicBool::new(false);
static STARTED: OnceLock<Instant> = OnceLock::new();

/// Errors the log got so far (an item compares the number before and after it ran).
pub fn error_count() -> u32 {
    ERRORS.load(Ordering::Relaxed)
}

/// The debug log. The file stays open for the whole run and every line is one write, so nothing is lost when the
/// program ends with `process::exit`.
///
/// An event is one line: `time +seconds-since-the-previous-line PHASE #item LEVEL text`. The level says how it
/// went: `INFO` what happens, `OK` an operation that worked, `WARN` something odd that did not stop the item,
/// `ERR` an operation that failed, `MSG` a message the user was shown.
pub struct Logger {
    file: RefCell<std::fs::File>,
    last: Cell<Instant>,
}

impl Logger {
    pub fn open(path: &str) -> Option<Logger> {
        let f = std::fs::OpenOptions::new().create(true).append(true).open(path).ok()?;
        if let Ok(mut p) = LOG_PATH.lock() {
            *p = Some(path.to_string());
        }
        let _ = STARTED.set(Instant::now());
        Some(Logger { file: RefCell::new(f), last: Cell::new(Instant::now()) })
    }

    /// A line as it is (the header and the lists).
    pub fn write(&self, text: &str) {
        use std::io::Write;
        let mut line = String::with_capacity(text.len() + 1);
        line.push_str(text);
        line.push('\n');
        let _ = self.file.borrow_mut().write_all(line.as_bytes());
    }

    pub fn event(&self, phase: &str, item: usize, level: &str, text: &str) {
        match level {
            "ERR" => ERRORS.fetch_add(1, Ordering::Relaxed),
            "WARN" => WARNINGS.fetch_add(1, Ordering::Relaxed),
            _ => 0,
        };
        let now = Instant::now();
        let gap = now.duration_since(self.last.replace(now)).as_secs_f64();
        let t = util::local_now();
        let item = if item == 0 { String::new() } else { format!("#{}", item) };
        self.write(&format!(
            "{:02}:{:02}:{:02}.{:03} +{:<7.3} {:<6} {:<4} {:<4} {}",
            t.hour,
            t.min,
            t.sec,
            t.ms,
            gap,
            phase,
            item,
            level,
            text
        ));
    }
}

/// Writes the line that ends the debug log, once (when there is a log).
pub fn log_end(code: i32) {
    if ENDED.swap(true, Ordering::Relaxed) {
        return;
    }
    let Some(path) = LOG_PATH.lock().ok().and_then(|p| p.clone()) else { return };
    let Ok(mut f) = std::fs::OpenOptions::new().append(true).open(path) else { return };
    use std::io::Write;
    let secs = STARTED.get().map_or(0.0, |s| s.elapsed().as_secs_f64());
    let _ = writeln!(
        f,
        "\nEND  exit={}  errors={}  warnings={}  elapsed={:.1}s",
        code,
        ERRORS.load(Ordering::Relaxed),
        WARNINGS.load(Ordering::Relaxed),
        secs
    );
}

pub struct Ctx {
    pub script_full: String,
    pub script_dir: String,
    pub exe_name: String,
    pub title: String,
    pub ini_path: String,
    /// The .ini, loaded once (after the program knows it exists).
    pub ini: IniDoc,
    /// SHA-1 of the executable; only computed when something needs it (see `file_hash`).
    file_hash: OnceCell<String>,
    pub cmd_raw: String,
    pub os_arch: &'static str,
    /// Architecture of the chosen main application: "x64" only if the 2nd segment of
    /// `application` was chosen, "x86" otherwise.
    pub app_arch: &'static str,

    pub is_readonly: bool,
    pub first_instance: bool,
    pub run_after: bool,
    pub wait_main: bool,
    pub debug: Option<Logger>,
    /// What the debug log says the program is doing: INIT, BEFORE, RUN, WAIT or AFTER, and the number of the
    /// `.ini` item that is running (0 = none).
    pub phase: Cell<&'static str>,
    pub item: Cell<usize>,
    /// Registry keys and values whose export to the `.reg` failed: their AFTER steps leave them as they are.
    pub unsaved: RefCell<Vec<String>>,
    /// Texts that came out of encrypted tokens: the debug log never shows them.
    secrets: RefCell<Vec<String>>,

    pub vars: Vec<(String, String)>,
    /// Value of each entry of `SHELL_FOLDERS`; `None` until it is used for the first time.
    shell: Vec<Option<String>>,

    pub main_app: Option<String>,
    pub main_cmdline: String,
    pub main_workdir: String,
    pub show_state: u16,
    pub waitprocess: String,

    pub before: Vec<TaskKind>,
    pub after: Vec<TaskKind>,
    /// Automatic tasks of the AFTER section ("PROG" lines): always before the user's.
    pub after_prog: Vec<Prog>,
    pub pw_cache: Option<String>,
    /// While true `msg` shows nothing: the check that runs the arguments of the BEFORE items before they run (see
    /// `tasks::stop_on_leftover_backups`) must not show a message that the item shows again when it runs.
    pub quiet: Cell<bool>,
    /// Receives the command lines sent by the other instances (only the first instance has it).
    pub ipc: Option<ipc::Server>,
}

impl Ctx {
    pub fn new() -> Ctx {
        let exe = std::env::current_exe().map(|p| p.to_string_lossy().to_string()).unwrap_or_default();
        let exe = exe.trim_start_matches("\\\\?\\").to_string();
        let script_full = util::path_full(&exe, "C:\\");
        let (dir, file) = util::split_parent(&script_full);
        let script_dir = if dir.len() == 2 && dir.ends_with(':') { format!("{}\\", dir) } else { dir };
        let exe_name = match file.rfind('.') {
            Some(i) if i > 0 => file[..i].to_string(),
            _ => file.clone(),
        };
        let title = format!("{} - {}", exe_name, PROGRAM_NAME);
        let ini_path = format!("{}\\{}.ini", script_dir.trim_end_matches('\\'), exe_name);
        let mut c = Ctx {
            script_full,
            script_dir,
            exe_name,
            title,
            ini_path,
            ini: IniDoc::empty(),
            file_hash: OnceCell::new(),
            cmd_raw: sys::cmdline_raw(),
            os_arch: sys::os_arch(),
            app_arch: "x86",
            is_readonly: false,
            first_instance: true,
            run_after: true,
            wait_main: true,
            debug: None,
            phase: Cell::new("INIT"),
            item: Cell::new(0),
            unsaved: RefCell::new(Vec::new()),
            secrets: RefCell::new(Vec::new()),
            vars: Vec::new(),
            shell: vec![None; SHELL_FOLDERS.len()],
            main_app: None,
            main_cmdline: String::new(),
            main_workdir: String::new(),
            show_state: 5,
            waitprocess: String::new(),
            before: Vec::new(),
            after: Vec::new(),
            after_prog: Vec::new(),
            pw_cache: None,
            quiet: Cell::new(false),
            ipc: None,
        };
        c.init_vars();
        c
    }

    /// SHA-1 of the executable (it names the single-instance objects).
    pub fn file_hash(&self) -> &str {
        self.file_hash.get_or_init(|| crypto::sha1_file(&self.script_full))
    }

    /// `VarFuncIni()`: initial value macros.
    fn init_vars(&mut self) {
        let root = self.script_dir.trim_end_matches('\\').to_string();
        let drive: String = self.script_dir.chars().take(1).collect();
        self.add_var("GAPROOT", &root);
        self.add_var("DRIVE", &drive);
        self.add_var("LINEBREAK", "\r\n");
        self.add_var("PARAMETERS", &self.cmd_raw.clone());
        self.add_var("OSARCH", self.os_arch);
    }

    /// Value of the shell folder `SHELL_FOLDERS[i]`: read from "Shell Folders" (HKCU/HKLM) the first time it is
    /// used, with the shell API as a fallback when the registry value does not exist.
    pub fn shell_value(&mut self, i: usize) -> &str {
        if self.shell[i].is_none() {
            let (name, csidl, hklm) = SHELL_FOLDERS[i];
            let key = if hklm {
                "HKLM\\Software\\Microsoft\\Windows\\CurrentVersion\\Explorer\\Shell Folders"
            } else {
                "HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Explorer\\Shell Folders"
            };
            let val = reg::read_string(key, name, reg::View::Native)
                .filter(|s| !s.is_empty())
                .or_else(|| sys::csidl_path(csidl))
                .unwrap_or_default();
            self.shell[i] = Some(val);
        }
        self.shell[i].as_deref().unwrap_or("")
    }

    /// Every shell folder as (name, value): only the debug log needs them all.
    pub fn shell_all(&mut self) -> Vec<(String, String)> {
        (0..SHELL_FOLDERS.len()).map(|i| (SHELL_FOLDERS[i].0.to_string(), self.shell_value(i).to_string())).collect()
    }

    /// "Common AppData" with a trailing backslash (where the program writes when its own drive is read only).
    pub fn common_appdata(&mut self) -> String {
        let i = SHELL_FOLDERS.iter().position(|(n, _, _)| *n == "Common AppData").unwrap_or(0);
        format!("{}\\", self.shell_value(i))
    }

    pub fn add_var(&mut self, name: &str, value: &str) {
        if let Some(e) = self.vars.iter_mut().find(|(n, _)| n == name) {
            e.1 = value.to_string();
        } else {
            self.vars.push((name.to_string(), value.to_string()));
        }
    }

    pub fn get_var(&self, name: &str) -> Option<&str> {
        self.vars.iter().find(|(n, _)| n == name).map(|(_, v)| v.as_str())
    }

    pub fn msg(&self, text: &str) {
        if !self.quiet.get() {
            self.emit("MSG", &text.replace("\r\n", " | ").replace('\n', " | "));
            ui::info(&self.title, text);
        }
    }

    /// From now on the debug log shows `***` where `secret` (the text of a decrypted token) would be.
    pub fn hide_in_log(&self, secret: &str) {
        if !secret.is_empty() && self.debug.is_some() {
            self.secrets.borrow_mut().push(secret.to_string());
        }
    }

    fn scrub(&self, text: &str) -> String {
        let mut t = text.to_string();
        for s in self.secrets.borrow().iter() {
            t = t.replace(s.as_str(), "***");
        }
        t
    }

    fn emit(&self, level: &str, text: &str) {
        if let Some(l) = &self.debug {
            l.event(self.phase.get(), self.item.get(), level, &self.scrub(text));
        }
    }

    /// Debug log: what happens.
    pub fn log(&self, text: &str) {
        self.emit("INFO", text);
    }

    /// Debug log: an operation that worked.
    pub fn ok(&self, text: &str) {
        self.emit("OK", text);
    }

    /// Debug log: something odd that did not stop the item.
    pub fn warn(&self, text: &str) {
        self.emit("WARN", text);
    }

    /// Debug log: an operation that failed.
    pub fn err(&self, text: &str) {
        self.emit("ERR", text);
    }

    /// Debug log: a line as it is, without the columns (the lists of items and variables).
    pub fn raw(&self, text: &str) {
        if let Some(l) = &self.debug {
            l.write(&self.scrub(text));
        }
    }

    /// Writes a failure that the program does not show to the debug log.
    pub fn log_err(&self, what: &str, err: &dyn std::fmt::Display) {
        self.err(&format!("{}: {}", what, err));
    }

    /// A path as the main application sees it (see `util::rewrite_system32`).
    pub fn io_path(&self, p: &str) -> String {
        sys::io_path(self.app_arch, p)
    }

    /// Default message for "function called in the wrong section".
    pub fn wrong_section(&self, kw: &str, section: Section) {
        self.msg(&format!("The \"{}\" function can't be called from the \"{}\" section.", kw, section.name()));
    }
}

/// Exit codes. They are `0` for a run that ended normally and different values for the ways it can end early, so
/// a script that starts gaP can tell them apart.
pub const EXIT_CONFIG: i32 = 2; // the .ini or the path of the main application is wrong
pub const EXIT_REQUIREMENT: i32 = 3; // a requirement of the main application is not met (administrator, OS, Java...)
pub const EXIT_CANCELLED: i32 = 4; // the user cancelled a question or a password
pub const EXIT_RUNNING: i32 = 5; // another instance is already running
pub const EXIT_NOT_DELIVERED: i32 = 6; // the running instance did not receive the command line of this one
pub const EXIT_BACKUP: i32 = 7; // a `_backup` item of an earlier run is still there: its original data was not restored

/// `Exit`: quits without additional cleanup (as in AutoIt), with code 0.
pub fn exit_now() -> ! {
    exit_code(0)
}

/// Quits without additional cleanup with the given exit code.
pub fn exit_code(code: i32) -> ! {
    log_end(code);
    std::process::exit(code)
}
